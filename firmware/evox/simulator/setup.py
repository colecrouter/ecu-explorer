"""Build pinned GNU libsim locally; no global install or adjacent repository."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import subprocess
import struct
import sys
import tarfile
import urllib.request

ROOT = Path(__file__).resolve().parents[3]
DEFAULT = ROOT / '.cache/evox-simulator'
LOCK = Path(__file__).with_name('engine-lock.json')


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_installation(work, lock):
    saved = json.loads((work / 'installation.json').read_text())
    if saved['archive_sha256'] != lock['archive_sha256']: raise ValueError('cached release mismatch')
    if set(saved['files']) != set(lock['files']): raise ValueError('incomplete installation')
    for kind, expected_files in lock['files'].items():
        files = saved['files'][kind]
        if set(files) != set(expected_files): raise ValueError('incomplete artifact inventory')
        base = work / ('gdb-16.3' if kind == 'source' else 'build')
        for name, expected in files.items():
            if kind == 'source' and expected != expected_files[name]: raise ValueError('upstream source mismatch')
            if digest(base / name) != expected: raise ValueError('cached artifact changed: ' + name)
    return saved


def smoke(work, lock):
    source, build = work / 'gdb-16.3', work / 'build'
    def run(argv, name):
        with (work / (name + '.log')).open('w') as log:
            subprocess.run(argv, stdout=log, stderr=subprocess.STDOUT, check=True)
    # Exercise the same public libsim API as the firmware harness before sealing.
    compiler = os.environ.get('CC', 'cc')
    argv = [compiler, '-std=c11', '-O2', '-Wall', '-Wextra', '-Werror',
            '-include', str(build / 'sim/config.h'), '-I', str(source / 'include'),
            '-I', str(build / 'bfd'), '-I', str(source / 'bfd'),
            str(Path(__file__).with_name('runner.c'))]
    argv += [str(build / name) for name in lock['files']['build'] if name.endswith('.a')]
    if Path('/opt/homebrew/lib').is_dir(): argv += ['-L/opt/homebrew/lib']
    argv += ['-lz', '-lzstd', '-lm']
    if sys.platform == 'darwin': argv += ['-liconv']
    argv += ['-o', str(work / 'smoke-runner')]
    run(argv, 'smoke-compile')
    registers = [0] * 24
    registers[14], registers[15], registers[21] = 0x8000, 0x30400, 0x1000
    packet = struct.pack('>4I24I', 1, 0x1000, 4, 16, *registers)
    packet += bytes.fromhex('1fcef000') + bytes(4096 + 1024)
    result = subprocess.run([work / 'smoke-runner'], input=packet, capture_output=True, check=True)
    row = json.loads(result.stdout)
    if row['status'] != 'return' or row['after'][21] != 0x8000:
        raise ValueError('GNU execution smoke failed')
    (work / 'smoke.json').write_bytes(result.stdout)


def setup(work, jobs):
    lock = json.loads(LOCK.read_text())
    work.mkdir(parents=True, exist_ok=True)
    manifest = work / 'installation.json'
    if manifest.exists():
        verify_installation(work, lock)
        smoke(work, lock)
        print('Verified simulator cache: ' + str(work)); return
    archive = work / 'gdb-16.3.tar.xz'
    if not archive.exists():
        temporary = work / 'download.partial'
        urllib.request.urlretrieve('https://ftp.gnu.org/gnu/gdb/gdb-16.3.tar.xz', temporary)
        temporary.replace(archive)
    if digest(archive) != lock['archive_sha256']: raise ValueError('GNU archive hash mismatch')
    source = work / 'gdb-16.3'
    if not source.exists():
        with tarfile.open(archive) as tar: tar.extractall(work, filter='data')
    # Verify public API/ISA headers against the reviewed upstream source pins.
    for name, expected in lock['files']['source'].items():
        if digest(source / name) != expected: raise ValueError('source pin mismatch: ' + name)
    build = work / 'build'; build.mkdir(exist_ok=True)
    commands = []
    def run(argv, name):
        commands.append(list(map(str, argv)))
        (work / 'commands.json').write_text(json.dumps(commands, indent=2) + '\n')
        with (work / (name + '.log')).open('w') as log:
            subprocess.run(argv, cwd=build, stdout=log, stderr=subprocess.STDOUT, check=True)
    run(['sh', str(source / 'configure'), '--target=m32r-elf', '--disable-gdb',
         '--disable-gdbserver', '--disable-binutils', '--disable-gas', '--disable-ld',
         '--disable-gprof', '--disable-gold', '--disable-nls', '--without-guile',
         '--without-python', '--with-system-zlib', '--disable-werror', 'MAKEINFO=true'], 'configure')
    # GNU make module generator needs a command terminator with BSD sed.
    makefile = build / 'sim/Makefile'
    # This file is generated by the first make invocation on some hosts.
    run(['make', '-j' + str(jobs), 'configure-sim'], 'configure-sim')
    if platform.system() == 'Darwin':
        text = makefile.read_text()
        makefile.write_text(text.replace(';p}', ';p;}'))
    run(['make', '-j' + str(jobs), 'all-sim'], 'build')
    smoke(work, lock)
    files = {kind: {name: digest((source if kind == 'source' else build) / name)
                    for name in names} for kind, names in lock['files'].items()}
    manifest.write_text(json.dumps(dict(schema_version=1, engine=lock['engine'],
        archive_sha256=lock['archive_sha256'], host=platform.platform(), files=files), indent=2) + '\n')
    print('Built simulator: ' + str(work))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--work', type=Path, default=DEFAULT)
    parser.add_argument('--jobs', type=int, default=min(os.cpu_count() or 2, 8))
    args = parser.parse_args()
    if args.jobs < 1: parser.error('--jobs must be positive')
    setup(args.work.resolve(), args.jobs)
